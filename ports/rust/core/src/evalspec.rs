//! The policy-evaluation vectors in `spec/conformance/eval/cases.json`.
//!
//! Other ports evaluate Cedar's JSON policy form with their own code. This
//! module is the referee: it runs each case through the real Cedar engine, so
//! "what Cedar does" is recorded once and every port is held to it.

use crate::{Error, Result};
use cedar_policy::{Authorizer, Context, Decision, Entities, EntityId, EntityTypeName, EntityUid, Policy, PolicyId, PolicySet, Request};
use serde_json::{json, Map, Value};
use std::str::FromStr;

fn uid(v: &Value) -> Result<EntityUid> {
    let ty = v[0].as_str().unwrap_or("");
    let t = EntityTypeName::from_str(ty).map_err(|e| Error::new("eval_case", format!("entity type '{ty}': {e}")))?;
    Ok(EntityUid::from_type_name_and_id(t, EntityId::from_str(v[1].as_str().unwrap_or("")).unwrap()))
}

/// Cedar text -> {id: policy JSON}. Ids come from `@id`.
pub fn to_json(src: &str) -> Result<Map<String, Value>> {
    let set = PolicySet::from_str(src).map_err(|e| Error::new("eval_case", e.to_string()))?;
    let mut out = Map::new();
    for p in set.policies() {
        let id = p.annotation("id").ok_or_else(|| Error::new("eval_case", "every policy needs @id"))?.to_string();
        out.insert(id, p.to_json().map_err(|e| Error::new("eval_case", e.to_string()))?);
    }
    Ok(out)
}

/// Real Cedar's answer for one case: decision, deciding policies, erroring policies.
pub fn evaluate(policies: &Map<String, Value>, entities: &Value, request: &Value) -> Result<Value> {
    let mut set = PolicySet::new();
    for (id, est) in policies {
        let p = Policy::from_json(Some(PolicyId::new(id)), est.clone()).map_err(|e| Error::new("eval_case", format!("{id}: {e}")))?;
        set.add(p).map_err(|e| Error::new("eval_case", e.to_string()))?;
    }
    let ents = Entities::from_json_value(entities.clone(), None).map_err(|e| Error::new("eval_case", e.to_string()))?;
    let ctx = Context::from_json_value(request.get("context").cloned().unwrap_or_else(|| json!({})), None).map_err(|e| Error::new("eval_case", e.to_string()))?;
    let action = json!(["Action", request["action"]]);
    let req = Request::new(uid(&request["principal"])?, uid(&action)?, uid(&request["resource"])?, ctx, None).map_err(|e| Error::new("eval_case", e.to_string()))?;
    let resp = Authorizer::new().is_authorized(&req, &set, &ents);
    let mut reasons: Vec<String> = resp.diagnostics().reason().map(|p| p.to_string()).collect();
    reasons.sort();
    let mut errors: Vec<String> = resp
        .diagnostics()
        .errors()
        .map(|e| {
            let cedar_policy::AuthorizationError::PolicyEvaluationError(pe) = e;
            pe.policy_id().to_string()
        })
        .collect();
    errors.sort();
    Ok(json!({"decision": if resp.decision() == Decision::Allow { "allow" } else { "deny" }, "reasons": reasons, "errors": errors}))
}

/// Source cases (Cedar text) -> the published vectors (policy JSON + Cedar's answer).
pub fn generate(source: &Value) -> Result<Value> {
    let entities = source["entities"].clone();
    let mut cases = Vec::new();
    for c in source["cases"].as_array().ok_or_else(|| Error::new("eval_case", "no cases"))? {
        let name = c["name"].as_str().unwrap_or("?");
        let policies = to_json(c["cedar"].as_str().unwrap_or("")).map_err(|e| Error::new("eval_case", format!("{name}: {}", e.message)))?;
        let mut out = json!({"name": name, "cedar": c["cedar"], "policies": policies, "request": c["request"]});
        if c["unsupported"] == json!(true) {
            // valid Cedar that the portable subset leaves out: ports must
            // refuse to load it rather than guess
            out["expect"] = json!({"load_error": true});
        } else {
            out["expect"] = evaluate(&policies, &entities, &c["request"]).map_err(|e| Error::new("eval_case", format!("{name}: {}", e.message)))?;
        }
        cases.push(out);
    }
    Ok(json!({"about": "Generated by `smartdelegate spec eval-gen` from cases.src.json. `expect` is the real Cedar engine's answer. Do not edit by hand.", "entities": entities, "cases": cases}))
}

/// Check the published vectors against real Cedar. Returns mismatches.
pub fn verify(doc: &Value) -> Result<Vec<String>> {
    let mut bad = Vec::new();
    for c in doc["cases"].as_array().ok_or_else(|| Error::new("eval_case", "no cases"))? {
        let name = c["name"].as_str().unwrap_or("?").to_string();
        let from_text = to_json(c["cedar"].as_str().unwrap_or(""))?;
        if Some(&from_text) != c["policies"].as_object() {
            bad.push(format!("{name}: policy JSON does not match the Cedar text"));
        }
        if c["expect"]["load_error"] == json!(true) {
            continue;
        }
        let got = evaluate(&from_text, &doc["entities"], &c["request"])?;
        if got != c["expect"] {
            bad.push(format!("{name}: Cedar says {got}, file says {}", c["expect"]));
        }
    }
    Ok(bad)
}
