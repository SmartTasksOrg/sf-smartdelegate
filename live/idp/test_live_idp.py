def _sh(*args: str, timeout: int) -> subprocess.CompletedProcess:
    return subprocess.run(["bash", KEYCLOAK_SH, *args], capture_output=True, text=True, timeout=timeout)


def setUpModule():
    global A, P, CO, URL, REALM, VERSION, STARTED
    if shutil.which("bash") is None:
        raise unittest.SkipTest("live Keycloak tests skipped: bash is needed to run live/idp/keycloak.sh")
    try:
        if not os.environ.get("SD_KEYCLOAK_URL") and _sh("status", timeout=60).returncode != 0:
            r = _sh("start", timeout=int(os.environ.get("SD_KEYCLOAK_START_TIMEOUT", "240")) + 1000)
            if r.returncode != 0:
                why = (r.stderr.strip().splitlines() or ["keycloak.sh start failed"])[-1]
                raise unittest.SkipTest(f"live Keycloak tests skipped: Keycloak could not be obtained or started ({why})")
            STARTED = True
        P = provision.provision(log=lambda m: None)
        A = kc.Admin.connect()
    except subprocess.TimeoutExpired:
        raise unittest.SkipTest("live Keycloak tests skipped: keycloak.sh did not finish in time") from None
    except kc.Unavailable as e:
        raise unittest.SkipTest(f"live Keycloak tests skipped: {e}") from None
    CO = provision.company()
    URL, REALM, VERSION = A.url, P["realm"], P["keycloak_version"]


def tearDownModule():
    if want_transcript() and TRANSCRIPT.order:
        TRANSCRIPT.write(HERE / "TRANSCRIPT.md")
    if STARTED and not os.environ.get("SD_KEYCLOAK_KEEP"):
        _sh("stop", timeout=120)


# ---- helpers ---------------------------------------------------------------------

def outcome(r: dict) -> str:
    """"ok" / "allow" / "deny:<reason>" / "error:<code>", as the harness scenarios write it."""
    if r.get("ok") is not True:
        return "error:" + (r.get("error") or {}).get("code", "?")
    if "effect" in r:
        return "allow" if r["effect"] == "allow" else "deny:" + str(r.get("reason"))
    return "ok"


def visible_paths(data, prefix="") -> set:
    out = set()
    if isinstance(data, dict):
        for k, v in data.items():
            if v == "[REDACTED]":
                continue
            p = f"{prefix}.{k}" if prefix else k
            out.add(p)
            out |= visible_paths(v, p)
    elif isinstance(data, list):
        for el in data:
            out |= visible_paths(el, prefix + "[]")
    return out


def role_call(role: str, n: str = "live-1") -> dict:
    """agent and task under which the company lends `role`."""
    r = ROLES[role]
    return {"role": role, "agent": r["agents"][0], "task": r["tasks"][0].replace("*", n), "tenant": TENANT}


def tampered(jwt: str, change) -> str:
    """The same header and signature around a changed payload."""
    h, p, s = jwt.split(".")
    c = kc.claims_of(jwt)
    change(c)
    return ".".join([h, base64.urlsafe_b64encode(json.dumps(c, separators=(",", ":")).encode()).rstrip(b"=").decode(), s])


class Daemon:
    """`python -m sf_smartdelegate serve` on a free loopback port."""

    def __init__(self, config: dict, workdir: str):
        self.config_path = os.path.join(workdir, "daemon.json")
        self.config = {**config, "admin_key": ADMIN_KEY, "pep_key": PEP_KEY}
        self.proc = None
        self.start()

    def start(self):
        Path(self.config_path).write_text(json.dumps(self.config), encoding="utf-8")
        env = {**os.environ, "PYTHONPATH": str(ROOT / "src") + os.pathsep + os.environ.get("PYTHONPATH", "")}
        self.proc = subprocess.Popen([sys.executable, "-m", "sf_smartdelegate", "serve", "--config", self.config_path, "--listen", "127.0.0.1:0"],
                                     stderr=subprocess.PIPE, text=True, env=env)
        q: queue.Queue = queue.Queue()
        threading.Thread(target=lambda: q.put(self.proc.stderr.readline()), daemon=True).start()
        try:
            line = q.get(timeout=60)
        except queue.Empty:
            self.stop()
            raise RuntimeError("the smartdelegate daemon did not start within 60 s") from None
        m = re.search(r"http://(\S+)", line)
        if not m:
            self.stop()
            raise RuntimeError(f"the smartdelegate daemon did not start: {line}")
        self.url = "http://" + m.group(1)
        self.client = DaemonClient(self.url, pep_key=PEP_KEY, admin_key=ADMIN_KEY, timeout=30)

    def stop(self):
        if self.proc is not None:
            self.proc.kill()
            try:
                self.proc.wait(timeout=30)
            finally:
                self.proc.stderr.close()
                self.proc = None


class Live(unittest.TestCase):
    maxDiff = None

    def setUp(self):
        self.dir = tempfile.mkdtemp(prefix="smartdelegate-live-idp-")
        self.addCleanup(shutil.rmtree, self.dir, True)
        self._n = 0

    # -- Keycloak ----------------------------------------------------------------
    def sign_in(self, user: str, client: str = "sd-engine", scope: str = "openid") -> dict:
        r = kc.sign_in(URL, REALM, client, P["clients"][client], user, P["passwords"][user], scope)
        self.assertIn("id_token", r, f"{user} could not sign in on {client}: {r.get('error')} {r.get('error_description')}")
        return r

    def id_token(self, user: str, client: str = "sd-engine") -> str:
        return self.sign_in(user, client)["id_token"]

    def restore(self, *users: str) -> None:
        """Put users back to the provisioned baseline: enabled, admin-set attributes, the company's groups."""
        for user in users:
            uid = A.user_id(REALM, user)
            rep = A.get(f"/realms/{REALM}/users/{uid}")
            attrs = CO["users"][user]["attrs"]
            rep.update(enabled=True, attributes={"region": [attrs["region"]], "unit": [attrs["unit"]]})
            A.put(f"/realms/{REALM}/users/{uid}", rep)
            provision.set_groups(A, REALM, uid, {A.group_by_path(REALM, P["group_paths"][g])["id"] for g in P["direct"][user]})

    def changing(self, *users: str) -> None:
        """Declare that this test changes these users in Keycloak; they are restored afterwards."""
        self.addCleanup(self.restore, *users)

    def lifespan(self, seconds: int) -> None:
        """Set the realm's access-token lifespan, which is also the ID token's. Restored afterwards."""
        self.addCleanup(A.put, f"/realms/{REALM}", {"accessTokenLifespan": DEFAULT_LIFESPAN})
        A.put(f"/realms/{REALM}", {"accessTokenLifespan": seconds})

    def sync_token(self) -> str:
        r = kc.client_credentials(URL, REALM, "sd-sync", P["clients"]["sd-sync"])
        self.assertIn("access_token", r, r)
        return r["access_token"]

    # -- engine --------------------------------------------------------------------
    def idp(self, audience: str = "sd-engine", **over) -> dict:
        cfg = {"issuer": kc.issuer(URL, REALM), "audience": audience, "jwks": kc.jwks(URL, REALM), "user_claim": "preferred_username",
               "groups_claim": "groups", "group_map": P["group_map"]}
        cfg.update(over)
        return {k: v for k, v in cfg.items() if v is not None}

    def bundle(self) -> Path:
        self._n += 1
        d = Path(self.dir) / f"bundle{self._n}"
        shutil.copytree(COMPANY, d)
        return d

    def config(self, idp: dict | None = None, bundle: Path | None = None) -> dict:
        self._n += 1
        cfg = {"bundle_dir": str(bundle or self.bundle()), "state_dir": os.path.join(self.dir, f"state{self._n}"), "max_depth": 3,
               "issuer": "smartdelegate://live-idp", "idp": self.idp() if idp is None else idp}
        if not cfg["idp"]:       # idp={}: an engine without an identity provider
            del cfg["idp"]
        return cfg

    def engine(self, idp: dict | None = None, bundle: Path | None = None) -> Engine:
        e = Engine(self.config(idp, bundle))
        self.addCleanup(e.close)
        return e

    def daemon(self, config: dict) -> Daemon:
        d = Daemon(config, self.dir)
        self.addCleanup(d.stop)
        return d

    def issue(self, backend, id_token: str | None, role: str, n: str = "live-1", **extra) -> dict:
        body = {**role_call(role, n), **extra}
        if id_token is not None:
            body["id_token"] = id_token
        return backend.call("issue_token", body)

    def narrow(self, backend, parent: dict, actor: str, cap: dict) -> dict:
        cap = {**cap, "deny_labels": sorted(set(cap.get("deny_labels") or []) | set(parent["cap"].get("deny_labels") or [])),
               "deny_fields": sorted(set(cap.get("deny_fields") or []) | set(parent["cap"].get("deny_fields") or []))}
        return backend.call("exchange_token", {"subject_token": parent["token"], "actor": actor, "cap": cap})

    def call(self, backend, token: str, action: str, resource: str, *, attrs=None, context=None, data=None, strict=False) -> dict:
        path, _, rid = resource.partition("/")
        body = {"token": token, "action": action, "resource": {"path": path, "id": rid or "any", **({"attrs": attrs} if attrs else {})}}
        if context:
            body["context"] = context
        if strict:
            body["strict"] = True
        if data is not None:
            body["data"] = data
        return backend.call("filter" if data is not None else "authorize", body)

    def grp(self, backend, token: str) -> list:
        return [g["id"] for g in backend.call("inspect_token", {"token": token})["claims"].get("grp", [])]

    # -- directory sync ------------------------------------------------------------
    def fetch(self, **kw):
        return keycloak.fetch(URL, REALM, token_env=TOKEN_ENV, env={TOKEN_ENV: self.sync_token()}, **kw)

    def sync(self, bundle: Path, *, nested: str = "inherit", **kw) -> dict:
        """The function path: keycloak.fetch + directory.sync."""
        return directory.sync(self.fetch(inherit=nested == "inherit"), Path(bundle) / "entities.json", group_map=P["group_map"], attr_map=ATTR_MAP, **kw)

    def sync_cli(self, bundle: Path, *extra: str, env: dict | None = None, token: str | None = None) -> tuple:
        """`smartdelegate bridge sync-keycloak` as a subprocess -> (exit code, parsed stdout or None, stderr)."""
        gm, am = Path(self.dir) / "group_map.json", Path(self.dir) / "attr_map.json"
        gm.write_text(json.dumps(P["group_map"]), encoding="utf-8")
        am.write_text(json.dumps(ATTR_MAP), encoding="utf-8")
        argv = [sys.executable, "-m", "sf_smartdelegate", "bridge", "sync-keycloak", "--url", URL, "--realm", REALM, "--token-env", TOKEN_ENV,
                "--out", str(bundle), "--group-map", str(gm), "--attr-map", str(am), "--nested", "inherit", *extra]
        full = {**os.environ, "PYTHONPATH": str(ROOT / "src"), TOKEN_ENV: token or self.sync_token(), "NO_PROXY": "127.0.0.1,localhost",
                "no_proxy": "127.0.0.1,localhost", **(env or {})}
        p = subprocess.run(argv, capture_output=True, text=True, env=full, timeout=180)
        try:
            out = json.loads(p.stdout)
        except ValueError:
            out = None
        self.assertNotIn(full[TOKEN_ENV], p.stdout + p.stderr, "the admin token leaked into the output")
        return p.returncode, out, p.stderr


