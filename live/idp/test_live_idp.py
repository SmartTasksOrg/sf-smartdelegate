    def test_07_signing_key_rotation(self):
        """Keycloak gets a new signing key. The engine holds a copy of the JWKS; `reload` refreshes it."""
        jwks_file = Path(self.dir) / "jwks.json"
        jwks_file.write_text(json.dumps(kc.jwks(URL, REALM)), encoding="utf-8")
        d = self.daemon(self.config(self.idp(jwks=None, jwks_file=str(jwks_file))))
        pid = d.proc.pid
        old_token = self.id_token("anna")
        old_kid = kc.header_of(old_token)["kid"]
        self.assertEqual(outcome(self.issue(d.client, old_token, "support-agent")), "ok")

        self.add_key("sd-live-rotated", active=True)
        new_token = self.id_token("anna")
        new_kid = kc.header_of(new_token)["kid"]
        self.assertNotEqual(new_kid, old_kid, "Keycloak signs with the key of the highest priority")
        published = {k["kid"] for k in kc.jwks(URL, REALM)["keys"] if k.get("use") == "sig"}
        self.assertEqual(published, {old_kid, new_kid}, "the old key stays published: tokens already issued still verify")

        # 1. an unannounced rotation: the engine with the old JWKS refuses every NEW sign-in, for every user
        r = self.issue(d.client, new_token, "support-agent")
        self.assertEqual(outcome(r), "error:id_token_invalid", r)
        self.assertIn("no matching key", r["error"]["message"])
        self.assertEqual(outcome(self.issue(d.client, old_token, "support-agent")), "ok")     # tokens signed before the rotation still pass
        # 2. the new JWKS goes into jwks_file; reload needs the admin key
        jwks_file.write_text(json.dumps(kc.jwks(URL, REALM)), encoding="utf-8")
        self.assertEqual(outcome(self.issue(d.client, new_token, "support-agent")), "error:id_token_invalid", "a changed file alone changes nothing")
        self.assertEqual(DaemonClient(d.url, pep_key=PEP_KEY, timeout=30).call("reload", {})["error"]["code"], "unauthorized")
        # 3. POST /v1/admin/reload: the same process now knows both keys. No restart.
        self.assertTrue(d.client.call("reload", {})["ok"])
        self.assertEqual(outcome(self.issue(d.client, new_token, "support-agent")), "ok")
        self.assertEqual(outcome(self.issue(d.client, old_token, "support-agent")), "ok")
        self.assertEqual((d.proc.pid, d.proc.poll()), (pid, None))
        # 4. a JWKS file that does not load: the reload fails as a whole and the keys in force stay
        version = d.client.call("info", {})["policy_version"]
        for broken in ("{ this is not json", json.dumps({"keys": "none"})):
            jwks_file.write_text(broken, encoding="utf-8")
            r = d.client.call("reload", {})
            self.assertEqual(outcome(r), "error:invalid_config", r)
            self.assertEqual(outcome(self.issue(d.client, new_token, "support-agent")), "ok")
        self.assertEqual(d.client.call("info", {})["policy_version"], version)
        # 5. an EMPTY but well-formed JWKS is taken as given: every sign-in is refused until it is fixed
        jwks_file.write_text(json.dumps({"keys": []}), encoding="utf-8")
        self.assertTrue(d.client.call("reload", {})["ok"])
        self.assertEqual(outcome(self.issue(d.client, new_token, "support-agent")), "error:id_token_invalid")
        jwks_file.write_text(json.dumps(kc.jwks(URL, REALM)), encoding="utf-8")
        self.assertTrue(d.client.call("reload", {})["ok"])
        self.assertEqual(outcome(self.issue(d.client, new_token, "support-agent")), "ok")

    def test_08_rotation_without_an_outage(self):
        """The operator order that never refuses a sign-in: publish the new key as PASSIVE, refresh
        the engine's JWKS, reload, and only then make the key active. Later: retire the old key the same way."""
        jwks_file = Path(self.dir) / "jwks.json"
        jwks_file.write_text(json.dumps(kc.jwks(URL, REALM)), encoding="utf-8")
        d = self.daemon(self.config(self.idp(jwks=None, jwks_file=str(jwks_file))))
        pid = d.proc.pid
        old_kids = {k["kid"] for k in kc.jwks(URL, REALM)["keys"]}
        before = self.id_token("anna")
        component = self.add_key("sd-live-passive", active=False)
        # 1. passive: published in the JWKS, not used for signing yet
        new_kids = {k["kid"] for k in kc.jwks(URL, REALM)["keys"]} - old_kids
        self.assertEqual(len(new_kids), 1)
        self.assertIn(kc.header_of(self.id_token("anna"))["kid"], old_kids)
        self.assertEqual(outcome(self.issue(d.client, self.id_token("anna"), "support-agent")), "ok")
        # 2. the engine gets the JWKS with both keys through /v1/admin/reload
        jwks_file.write_text(json.dumps(kc.jwks(URL, REALM)), encoding="utf-8")
        self.assertTrue(d.client.call("reload", {})["ok"])
        self.assertEqual(outcome(self.issue(d.client, self.id_token("anna"), "support-agent")), "ok")
        # 3. the key becomes active: sign-ins are signed with it, and the engine already knows it
        rep = A.get(f"/realms/{REALM}/components/{component}")
        rep["config"]["active"] = ["true"]
        A.put(f"/realms/{REALM}/components/{component}", rep)
        t = self.id_token("anna")
        self.assertIn(kc.header_of(t)["kid"], new_kids)
        self.assertEqual(outcome(self.issue(d.client, t, "support-agent")), "ok")
        self.assertEqual(outcome(self.issue(d.client, before, "support-agent")), "ok")        # signed with the old key, still published
        # 4. retiring the old key from the engine's copy: tokens it signed stop passing at the reload
        only_new = {"keys": [k for k in kc.jwks(URL, REALM)["keys"] if k["kid"] in new_kids]}
        jwks_file.write_text(json.dumps(only_new), encoding="utf-8")
        self.assertTrue(d.client.call("reload", {})["ok"])
        self.assertEqual(outcome(self.issue(d.client, before, "support-agent")), "error:id_token_invalid")
        self.assertEqual(outcome(self.issue(d.client, t, "support-agent")), "ok")
        self.assertEqual((d.proc.pid, d.proc.poll()), (pid, None), "one daemon process throughout: never restarted")


