    def test_04_a_token_of_another_realm(self):
        """Same server, same client id, same username, same group path - another realm."""
        other = kc.sign_in(URL, P["other_realm"], "sd-engine", P["other"]["client_secret"], "anna", P["other"]["password"])
        self.assertIn("id_token", other, other)
        c = kc.claims_of(other["id_token"])
        self.assertEqual((c["aud"], c["preferred_username"], c["groups"]), ("sd-engine", "anna", ["/employees/support"]))
        self.assertEqual(c["iss"], kc.issuer(URL, P["other_realm"]))
        r = self.issue(self.engine(), other["id_token"], "support-agent")
        self.assertEqual(outcome(r), "error:id_token_invalid", r)                    # its key is not in our realm's JWKS
        self.assertIn("no matching key", r["error"]["message"])
        # even an engine that (wrongly) trusted the other realm's keys refuses the issuer
        r = self.issue(self.engine(self.idp(jwks=kc.jwks(URL, P["other_realm"]))), other["id_token"], "support-agent")
        self.assertEqual(outcome(r), "error:id_token_invalid", r)
        self.assertIn("issuer", r["error"]["message"])

    def test_05_a_tampered_token(self):
        e = self.engine()
        good = self.id_token("anna")
        self.assertEqual(outcome(self.issue(e, good, "support-agent")), "ok")
        forged = {
            "more groups": tampered(good, lambda c: c.__setitem__("groups", c["groups"] + ["/employees/support/support-supervisors"])),
            "another user": tampered(good, lambda c: c.__setitem__("preferred_username", "elena")),
            "later expiry": tampered(good, lambda c: c.__setitem__("exp", c["exp"] + 86400)),
            "signature cut": good[:-8],
            "signature of another token": good.rsplit(".", 1)[0] + "." + self.id_token("ben").rsplit(".", 1)[1],
            "alg none": base64.urlsafe_b64encode(b'{"alg":"none","typ":"JWT"}').rstrip(b"=").decode() + "." + good.split(".")[1] + ".",
        }
        for name, t in forged.items():
            with self.subTest(forgery=name):
                role = "support-supervisor" if name == "more groups" else "support-agent"
                self.assertEqual(outcome(self.issue(e, t, role)), "error:id_token_invalid")

    def test_06_an_expired_token(self):
        """The ID token lives exactly as long as the realm's access-token lifespan."""
        e = self.engine()
        self.lifespan(4)
        t = self.id_token("anna")
        c = kc.claims_of(t)
        self.assertEqual(c["exp"] - c["iat"], 4)
        self.assertEqual(outcome(self.issue(e, t, "support-agent")), "ok")
        time.sleep(max(0.0, c["exp"] - time.time()) + 1.2)
        r = self.issue(e, t, "support-agent")
        self.assertEqual(outcome(r), "error:id_token_invalid", r)
        self.assertIn("expired", r["error"]["message"])

