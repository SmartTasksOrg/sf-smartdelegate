class Transcript:
    """Collects the readable record of the end-to-end tests. Never holds a
    token, a password or a key: tokens are shown as a few claims only."""

    def __init__(self):
        self.sections: dict = {}
        self.order: list = []

    def section(self, title: str) -> list:
        if title not in self.sections:
            self.sections[title] = []
            self.order.append(title)
        return self.sections[title]

    def write(self, path: Path) -> None:
        out = ["# Live transcript: SmartDelegate against a real Keycloak", "",
               f"Generated by `live/idp/test_live_idp.py` on {datetime.date.today().isoformat()} against Keycloak {VERSION} "
               f"({'attached server' if os.environ.get('SD_KEYCLOAK_URL') else 'started by keycloak.sh'}), realm `{REALM}`.",
               "Every line below is what the real server and the real engine answered in that run. Tokens are shown as selected",
               "claims only; no token, password or key is in this file. The port in the issuer changes from run to run.", ""]
        for title in self.order:
            out += [f"## {title}", "", "```text", *self.sections[title], "```", ""]
        path.write_text("\n".join(out), encoding="utf-8", newline="\n")


